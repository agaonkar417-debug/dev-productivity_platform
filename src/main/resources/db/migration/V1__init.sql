-- DevFlow AI schema.
-- Portable SQL: runs on PostgreSQL (real app) and H2 (automated tests).

CREATE TABLE task_kit (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug           VARCHAR(80)  NOT NULL UNIQUE,
    name           VARCHAR(120) NOT NULL,
    description    TEXT,
    category       VARCHAR(60),
    minutes_saved  INTEGER      NOT NULL DEFAULT 0,
    built_in       BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE kit_file (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kit_id         BIGINT       NOT NULL REFERENCES task_kit (id) ON DELETE CASCADE,
    sort_order     INTEGER      NOT NULL,
    path_template  VARCHAR(500) NOT NULL,
    content        TEXT         NOT NULL
);

CREATE INDEX idx_kit_file_kit ON kit_file (kit_id);

CREATE TABLE generation_run (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kit_id         BIGINT REFERENCES task_kit (id) ON DELETE SET NULL,
    kit_name       VARCHAR(120)  NOT NULL,
    inputs_summary VARCHAR(1000) NOT NULL,
    file_count     INTEGER       NOT NULL,
    minutes_saved  INTEGER       NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_generation_run_created ON generation_run (created_at);
